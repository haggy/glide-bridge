#!/usr/bin/env python3
"""Build a data-collection launch config with Glidance's local costmap turned on.

Runs **on the robot** (Python 3.11, PyYAML ships with ROS). It reads Glidance's own
configs from ``/shared`` and writes the result to ``/data/glide_link``. Nothing from
``/shared`` is copied off the robot.

Result = ``glide_alpha2_dc.yaml`` (cameras 640x360 with depth registered to color,
6 fps, ``_rfps`` topics, ``/bag_record``) plus, taken unchanged from
``glide_alpha2.yaml``, the blocks the local costmap needs:

- ``camera_up`` / ``camera_down``: ``enable_point_cloud: true``
- ``ir_filter_camera_up`` / ``ir_filter_camera_down``: depth points -> ``/ir_filter_camera_*/points``
- ``traversability_filter_camera_down``, ``overhead_point_filter``: obstacle points for
  the costmap's traversability layer
- ``nav2``: Nav2 with Glidance's params (controller_server hosts ``/local_costmap``)

``goals_orchestrator`` stays disabled, so nothing sends Nav2 goals: Nav2's controller
stays idle and only the costmap runs. The bag recorder also records the costmap,
``/cmd_vel`` and TF.

Examples
--------
::

    # on the laptop (deploys, then runs this on the robot)
    ./glide_robot.sh deploy && ./glide_robot.sh nav config

Notes
-----
In data-collection mode, depth is registered to color (``/camera_*/depth/camera_info``
is the color K), but the IR images are not. The IR filter's over-exposure mask may be
offset by a few pixels from depth. That only matters in strong sunlight or near reflections.
"""

from __future__ import annotations

import argparse
import copy
import sys
from pathlib import Path

import yaml

CONFIG_DIR: Path = Path("/shared/glide_launchers/share/glide_launchers/config")
OUT: Path = Path("/data/glide_link/glide_alpha2_dc_nav.yaml")
FROM_NORMAL: tuple[str, ...] = ("nav2", "ir_filter_camera_up", "ir_filter_camera_down",
                                "traversability_filter_camera_down", "overhead_point_filter")
EXTRA_BAG_TOPICS: tuple[str, ...] = ("/local_costmap/costmap", "/local_costmap/costmap_updates",
                                     "/cmd_vel", "/tf", "/tf_static")


def build(normal: dict, dc: dict) -> dict:
    """``dc`` with the costmap pipeline from ``normal`` (see module docstring)."""
    out: dict = copy.deepcopy(dc)
    for key in FROM_NORMAL:
        if key not in normal:
            raise KeyError(f"{key} missing from the normal config; Glidance's layout changed")
        out[key] = copy.deepcopy(normal[key])
        out[key]["enable"] = True
    for cam in ("camera_up", "camera_down"):
        out[cam]["enable_point_cloud"] = True
    if out.get("goals_orchestrator", {}).get("enable"):
        raise ValueError("goals_orchestrator is enabled in the DC config; refusing (it sends Nav2 goals)")
    topics: list[str] = out["utils"]["rosbag_topics"]
    topics += [t for t in EXTRA_BAG_TOPICS if t not in topics]
    return out


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--out", type=Path, default=OUT)
    args = p.parse_args()
    normal: dict = yaml.safe_load(open(CONFIG_DIR / "glide_alpha2.yaml"))
    dc: dict = yaml.safe_load(open(CONFIG_DIR / "glide_alpha2_dc.yaml"))
    cfg = build(normal, dc)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    with open(args.out, "w") as fh:
        fh.write("# generated by make_nav_config.py: glide_alpha2_dc.yaml + costmap pipeline\n")
        yaml.safe_dump(cfg, fh, sort_keys=False)
    on = [k for k, v in cfg.items() if isinstance(v, dict) and v.get("enable")]
    print(f"wrote {args.out}\n  enabled: {', '.join(on)}\n"
          f"  cameras: up {cfg['camera_up'].get('color_width')}x{cfg['camera_up'].get('color_height')}, "
          f"point clouds on\n  bag topics +: {', '.join(EXTRA_BAG_TOPICS)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
